"""Run the held-out evaluation and write results/ (metrics.json, summary.md, skill.png)."""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from . import config  # noqa: E402
from .dataset import load_summary, make_pairs, split  # noqa: E402
from .features import TARGETS  # noqa: E402
from .model import (CLASSIFICATION, Predictors, confidence_report,  # noqa: E402
                    inference_latency_ms, score)

LABEL = {"duct_present": "Duct present (yes/no)", "trap_strength_m": "Duct strength (M-units)",
         "trap_thickness_m": "Duct thickness (m)"}


def run(leads=(12, 24), train_station=config.DEFAULT_STATION, stress_station=config.STRESS_STATION,
        raw_dir=config.RAW_DIR, processed_dir=config.PROCESSED_DIR, seeds: int = 5, rebuild: bool = False):
    sd = load_summary(train_station, raw_dir, processed_dir, rebuild)
    ad = load_summary(stress_station, raw_dir, processed_dir, rebuild)
    results = {
        "setup": {
            "train_station": f"{train_station} ({config.STATION_NAMES.get(train_station, '')})",
            "stress_station": f"{stress_station} ({config.STATION_NAMES.get(stress_station, '')})",
            "train_period": f"{config.START_YEAR}-01-01 to {config.TEST_START} (exclusive)",
            "test_period": f"{config.TEST_START} onward (never used for training or tuning)",
            "current_system_stand_in": "persistence: keep using the ducting state from the previous sounding",
            "leads_hours": list(leads), "nn": "5-member MLP ensemble (32,16), CPU only",
            "ducting_threshold_m_units": config.DUCT_MIN_STRENGTH_M,
        },
        "experiments": {},
    }
    for lead in leads:
        sd_tr, sd_te = split(make_pairs(sd, lead))
        ad_tr, ad_te = split(make_pairs(ad, lead))
        p_sd = Predictors(sd_tr, seeds)
        pred_sd = p_sd.predict(sd_te)
        exp = results["experiments"].setdefault(f"lead_{lead}h", {})
        exp["san_diego"] = {"n_train": int(len(sd_tr)), **score(sd_te, pred_sd)}
        exp["san_diego"]["confidence"] = confidence_report(sd_te, pred_sd)
        exp["san_diego"]["nn_latency_ms_per_sounding"] = round(inference_latency_ms(p_sd, sd_te), 1)

        p_ad = Predictors(ad_tr, seeds)
        pred_ad = p_ad.predict(ad_te)
        exp["abu_dhabi_local"] = {"n_train": int(len(ad_tr)), **score(ad_te, pred_ad)}
        pred_x = p_sd.predict(ad_te)
        # nn and gbm come from the San Diego-trained models; persistence and climatology stay local
        mixed = {t: {**pred_ad[t], "nn": pred_x[t]["nn"], "nn_std": pred_x[t]["nn_std"],
                     "gbm": pred_x[t]["gbm"]} for t in TARGETS}
        exp["abu_dhabi_transfer_from_san_diego"] = {"n_train": int(len(sd_tr)), **score(ad_te, mixed)}
    return results


def write_outputs(results: dict, out_dir=config.RESULTS_DIR) -> None:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "metrics.json").write_text(json.dumps(results, indent=2) + "\n")
    (out / "summary.md").write_text(_markdown(results))
    _figure(results, out / "skill.png")


def _fmt(t, m):
    return (f"Brier {m['brier']:.3f}, acc {m['accuracy']:.2f}, F1 {m['f1']:.2f}" if t in CLASSIFICATION
            else f"MAE {m['mae']:.1f}, RMSE {m['rmse']:.1f}")


def _skill(m, key):
    v = m.get(key)
    return "-" if v is None else f"{v:+.2f}"


def _markdown(res: dict) -> str:
    s = res["setup"]
    lines = ["# Results (auto-generated by `python -m utr evaluate`)", "",
             f"- Train station: {s['train_station']}", f"- Stress station: {s['stress_station']}",
             f"- Train: {s['train_period']}", f"- Test: {s['test_period']}",
             f"- 'Current system' stand-in: {s['current_system_stand_in']}", "",
             "Skill = 1 - (error of the model / error of the reference), using MSE (Brier for the duct flag). "
             "Positive means better than the reference; 0 means no better.", ""]
    names = {"san_diego": "San Diego (train and test on the same place)",
             "abu_dhabi_local": "Abu Dhabi, model trained on Abu Dhabi",
             "abu_dhabi_transfer_from_san_diego": "Abu Dhabi, nn/gbm trained ONLY on San Diego "
                                                 "(persistence and climatology use local Abu Dhabi history)"}
    for lead_key, exps in res["experiments"].items():
        lines += [f"## Lead {lead_key.split('_')[1]}", ""]
        for ekey, e in exps.items():
            lines += [f"### {names[ekey]}", "",
                      "| Target | Method | Error | Skill vs persistence | Skill vs climatology |",
                      "|---|---|---|---|---|"]
            for t in TARGETS:
                for meth in ("persistence", "climatology", "nn", "gbm"):
                    m = e[t][meth]
                    lines.append(f"| {LABEL[t]} | {meth} | {_fmt(t, m)} | {_skill(m, 'skill_vs_persistence')} "
                                 f"| {_skill(m, 'skill_vs_climatology')} |")
            lines.append("")
            lines.append("NN loss minus reference loss (negative = NN better), 95% CI over calendar months:")
            lines.append("")
            for t in TARGETS:
                for base in ("persistence", "climatology"):
                    d = e[t][f"nn_minus_{base}_loss"]
                    lines.append(f"- {LABEL[t]} vs {base}: {d['mean']:+.3f} [{d['ci95'][0]:+.3f}, {d['ci95'][1]:+.3f}]")
            lines.append("")
            if "confidence" in e:
                c = e["confidence"]
                lines += [f"Confidence check ({LABEL[c['target']]}): Spearman(spread, error) = "
                          f"{c['spearman_spread_vs_error']:+.2f}; MAE green/yellow/red = "
                          f"{c['mae_by_band']['green']:.1f} / {c['mae_by_band']['yellow']:.1f} / "
                          f"{c['mae_by_band']['red']:.1f}", "",
                          f"NN latency: {e['nn_latency_ms_per_sounding']} ms per new sounding "
                          f"(all three predictions, CPU).", ""]
    return "\n".join(lines) + "\n"


def _figure(res: dict, path: Path) -> None:
    exps = [("san_diego", "San Diego (test 2022+)"),
            ("abu_dhabi_transfer_from_san_diego", "Abu Dhabi: NN and GBM trained only on San Diego")]
    leads = list(res["experiments"].keys())
    fig, axes = plt.subplots(1, 2, figsize=(11, 4), sharey=True)
    colors = {"nn": "#1f6fb2", "gbm": "#7a7a7a", "climatology": "#d98324"}
    labels = {"nn": "Neural network", "gbm": "Gradient boosting (reference)", "climatology": "Climatology (local history)"}
    for ax, (ekey, title) in zip(axes, exps):
        groups = [(t, lk) for lk in leads for t in TARGETS]
        width = 0.26
        for j, meth in enumerate(("nn", "gbm", "climatology")):
            vals = [res["experiments"][lk][ekey][t][meth]["skill_vs_persistence"] for t, lk in groups]
            ax.bar([i + (j - 1) * width for i in range(len(groups))], vals, width,
                   color=colors[meth], label=labels[meth])
        ax.axhline(0, color="black", lw=0.8)
        ax.set_xticks(range(len(groups)))
        ax.set_xticklabels([f"{LABEL[t].split(' (')[0]}\n{lk.split('_')[1]}" for t, lk in groups],
                           fontsize=7)
        ax.set_title(title, fontsize=10)
    axes[0].set_ylabel("Skill vs persistence (current-system stand-in)\n(higher = better; 0 = no better)")
    axes[0].legend(fontsize=7, loc="lower left")
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)
